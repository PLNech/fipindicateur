import "C"

import (
	"encoding/json"
	"errors"
	"log"
	"runtime"
	"sync"
	"unsafe"
)

// Available reports whether this build carries the real panel. True here
// (linux && cgo); the stub is false, and the tray keeps its volume submenu.
const Available = true

const (
	panelWidth  = 380
	panelMargin = 12 // gap from the work area's top-right corner
	minHeight   = 200
	maxHeight   = 800
)

// gtkCalls carries closures to the GTK thread: fip_idle_add schedules one
// fipDrawerIdle dispatch per queued closure (g_idle_add is thread-safe, so
// this is the whole cross-thread story).
var gtkCalls = make(chan func(), 64)

// current is the process's one drawer, the target of the C signal callbacks
// (which carry no useful user_data across cgo). Guarded by currentMu.
var (
	currentMu sync.Mutex
	current   *Drawer
)

func currentDrawer() *Drawer {
	currentMu.Lock()
	defer currentMu.Unlock()
	return current
}

// Drawer is the resident panel window. Build once (first Show), then hide and
// re-present: reopening is instant. All exported methods are safe from any
// goroutine.
type Drawer struct {
	onCommand func(Command)
	onHide    func()

	mu          sync.Mutex
	lastState   State
	hasState    bool
	pendingView string // view requested before the page could take it
	started     bool   // GTK goroutine launched (protects reading ready/initErr)

	startOnce sync.Once
	ready     chan struct{}
	initErr   error

	// GTK-thread-only state after ready closes.
	win       *C.GtkWidget
	view      *C.WebKitWebView
	pageReady bool // the page ran its script and can accept fipState pushes
}

// New prepares a drawer. onCommand receives the page's user actions on a
// fresh goroutine (never the GTK thread); onHide (optional) fires whenever
// the panel hides (Escape, the page's close button, or an explicit Hide).
func New(onCommand func(Command), onHide func()) *Drawer {
	d := &Drawer{onCommand: onCommand, onHide: onHide, ready: make(chan struct{})}
	currentMu.Lock()
	current = d
	currentMu.Unlock()
	return d
}

// ensureStarted launches the dedicated GTK goroutine once and waits for the
// window to be built (or gtk_init to fail: headless, no DISPLAY).
func (d *Drawer) ensureStarted() error {
	d.startOnce.Do(func() {
		d.mu.Lock()
		d.started = true
		d.mu.Unlock()
		go func() {
			// GTK requires all its calls on one OS thread, forever.
			runtime.LockOSThread()
			if C.gtk_init_check(nil, nil) == 0 {
				d.initErr = errors.New("drawer: gtk_init a échoué (pas d'affichage ?)")
				close(d.ready)
				return
			}
			html := C.CString(pageHTML)
			var view *C.WebKitWebView
			d.win = C.fip_build(&view, html, panelWidth, 520)
			C.free(unsafe.Pointer(html)) // load_html copied it
			d.view = view
			close(d.ready)
			C.gtk_main()
		}()
	})
	<-d.ready
	return d.initErr
}

// Show builds the window on first use, pushes the given state and presents
// the panel at the top-right of the primary monitor's work area.
func (d *Drawer) Show(state State) error {
	d.mu.Lock()
	d.lastState = state
	d.hasState = true
	d.mu.Unlock()
	if err := d.ensureStarted(); err != nil {
		return err
	}
	d.runOnGTK(func() {
		d.evalStateLocked()
		C.fip_present(d.win, panelWidth, panelMargin)
	})
	return nil
}

// Push updates the page's state (visible or not) so the next look is always
// current. A no-op until the first Show built the window.
func (d *Drawer) Push(state State) {
	d.mu.Lock()
	d.lastState = state
	d.hasState = true
	started := d.started
	d.mu.Unlock()
	if !started {
		return
	}
	select {
	case <-d.ready:
	default:
		return // still initializing; Show will push
	}
	if d.initErr != nil {
		return
	}
	d.runOnGTK(func() { d.evalStateLocked() })
}

// SetView asks the page to switch to a named view ("main", "history",
// "settings"). Sticky until the page has run its script: a view requested
// alongside the very first Show is applied right after the initial state
// lands, so a right click can open straight onto Réglages.
func (d *Drawer) SetView(view string) {
	d.mu.Lock()
	d.pendingView = view
	started := d.started
	d.mu.Unlock()
	if !started {
		return // applied by the page's "ready" dispatch after Show
	}
	select {
	case <-d.ready:
	default:
		return
	}
	if d.initErr != nil {
		return
	}
	d.runOnGTK(func() { d.evalViewLocked() })
}

// evalViewLocked pushes the pending view request, if any. GTK thread only
// (the Locked suffix follows evalStateLocked's convention).
func (d *Drawer) evalViewLocked() {
	if !d.pageReady {
		return // the "ready" dispatch will re-run this
	}
	d.mu.Lock()
	view := d.pendingView
	d.pendingView = ""
	d.mu.Unlock()
	if view == "" {
		return
	}
	data, err := json.Marshal(view)
	if err != nil {
		return
	}
	script := C.CString("window.fipView && window.fipView(" + string(data) + ");")
	C.fip_eval(d.view, script)
	C.free(unsafe.Pointer(script))
}

// Eval runs a script in the page once it is ready. Test/dev plumbing (the
// selftest drives the page's buttons through it); the app itself pushes state
// only through Push/SetView.
func (d *Drawer) Eval(script string) {
	d.mu.Lock()
	started := d.started
	d.mu.Unlock()
	if !started {
		return
	}
	select {
	case <-d.ready:
	default:
		return
	}
	if d.initErr != nil {
		return
	}
	d.runOnGTK(func() {
		if !d.pageReady {
			return
		}
		cs := C.CString(script)
		C.fip_eval(d.view, cs)
		C.free(unsafe.Pointer(cs))
	})
}

// SetWindowTitle renames the toplevel. The dev harness uses it so a leftover
// mock window can never pass for the real panel.
func (d *Drawer) SetWindowTitle(title string) {
	d.mu.Lock()
	started := d.started
	d.mu.Unlock()
	if !started {
		return
	}
	select {
	case <-d.ready:
	default:
		return
	}
	if d.initErr != nil {
		return
	}
	t := C.CString(title)
	d.runOnGTK(func() {
		C.gtk_window_set_title((*C.GtkWindow)(unsafe.Pointer(d.win)), t)
		C.free(unsafe.Pointer(t))
	})
}

// Hide withdraws the panel (it stays resident for an instant reopen).
func (d *Drawer) Hide() {
	d.mu.Lock()
	started := d.started
	d.mu.Unlock()
	if !started || d.initErr != nil {
		return
	}
	d.runOnGTK(func() { d.hideOnGTK() })
}

// runOnGTK queues fn for the GTK thread. Safe from any goroutine.
func (d *Drawer) runOnGTK(fn func()) {
	gtkCalls <- fn
	C.fip_idle_add()
}

// evalStateLocked pushes the last state into the page. GTK thread only. The
// JSON is a valid JS literal (encoding/json escapes the U+2028/29 hazards),
// so it is injected verbatim into the window.fipState call.
func (d *Drawer) evalStateLocked() {
	if !d.pageReady {
		return // the page will ask (action "ready") once its script runs
	}
	d.mu.Lock()
	has := d.hasState
	state := d.lastState
	d.mu.Unlock()
	if !has {
		return
	}
	data, err := json.Marshal(state)
	if err != nil {
		log.Printf("drawer: marshal state: %v", err)
		return
	}
	script := C.CString("window.fipState(" + string(data) + ");")
	C.fip_eval(d.view, script)
	C.free(unsafe.Pointer(script))
}

// hideOnGTK hides the window and fires onHide. GTK thread only.
func (d *Drawer) hideOnGTK() {
	C.gtk_widget_hide(d.win)
	if d.onHide != nil {
		go d.onHide()
	}
}

// dispatch routes a page message. Internal actions (ready/height/hide) are
// the drawer's own plumbing; everything else is a user command handed to the
// app off the GTK thread. GTK thread only.
func (d *Drawer) dispatch(cmd Command) {
	switch cmd.Action {
	case "ready":
		d.pageReady = true
		d.evalStateLocked()
		d.evalViewLocked()
	case "height":
		// Content-driven height, reported by the page after each render.
		h := cmd.Value
		if h < minHeight {
			h = minHeight
		}
		if h > maxHeight {
			h = maxHeight
		}
		C.fip_resize(d.win, panelWidth, C.int(h))
	case "hide":
		d.hideOnGTK()
	default:
		if d.onCommand != nil {
			go d.onCommand(cmd)
		}
	}
}
