package drawer

// The real panel: an undecorated GTK3 toplevel hosting one WebKitWebView,
// linked directly against the system webkit2gtk-4.1 + gtk+-3.0 through
// pkg-config (hand-rolled cgo, the internal/player idiom; no Go modules).
//
// Threading contract: gtk_init + gtk_main run on ONE dedicated goroutine with
// the OS thread locked; every later GTK/WebKit call is marshaled onto that
// thread through g_idle_add draining the gtkCalls channel. fyne/systray on
// Linux speaks DBus StatusNotifier and runs no GTK loop of its own, so the two
// coexist (verified at runtime on GNOME/X11).

